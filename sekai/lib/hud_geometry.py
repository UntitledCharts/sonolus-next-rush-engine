"""Shared HUD anchors and sprite geometry."""

REFERENCE_WIDTH = 1920
REFERENCE_HEIGHT = 1080
REFERENCE_ASPECT = REFERENCE_WIDTH / REFERENCE_HEIGHT
REFERENCE_PIXELS_PER_UNIT = 108
ANCHOR_INSET = 0.1
SAFE_AREA_SIDE_PADDING_PIXELS = 60
REFERENCE_HALF_HEIGHT = REFERENCE_HEIGHT / (2 * REFERENCE_PIXELS_PER_UNIT)


def hud_unit(aspect: float) -> float:
    return min(1.0, aspect / REFERENCE_ASPECT) / REFERENCE_HALF_HEIGHT


def hud_anchor(aspect: float, safe_aspect: float, right: bool) -> tuple[float, float]:
    top = 1 - ANCHOR_INSET * hud_unit(aspect)
    x = top * safe_aspect * (1 if right else -1)
    return x, top


